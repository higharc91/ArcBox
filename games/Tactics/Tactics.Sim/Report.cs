using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using Tactics.Logic;

namespace Tactics.Sim;

/// <summary>
/// The Markdown balance report (spec §5.6) for a sweep's battles, in seven sections (<see cref="Headings"/>), with the
/// flags the global constraints set: win rates below <see cref="LowWinRate"/> or above <see cref="HighWinRate"/>, battle
/// lengths outside <see cref="TargetRounds"/>, role-band values more than <see cref="BandTolerance"/> from their band's
/// mean, and abilities used in fewer than <see cref="RareUse"/> of the turns they were legal in. Deterministic: the same
/// battles give the same text.
/// </summary>
public static class Report
{
    /// <summary>A win rate below this is flagged.</summary>
    public const double LowWinRate = 0.60;

    /// <summary>A win rate above this is flagged.</summary>
    public const double HighWinRate = 0.95;

    /// <summary>The target battle length in rounds (inclusive).</summary>
    public static readonly (int Min, int Max) TargetRounds = (8, 12);

    /// <summary>How far from its band's mean a class's band measure may be.</summary>
    public const double BandTolerance = 0.15;

    /// <summary>An ability used in fewer than this share of the turns it was legal in is flagged.</summary>
    public const double RareUse = 0.02;

    /// <summary>The report's section headings, in order.</summary>
    public static ImmutableArray<string> Headings { get; } =
    [
        "## 1. Summary", "## 2. Win rate by encounter and level", "## 3. Rounds per battle", "## 4. Role bands",
        "## 5. Rarely used abilities", "## 6. Downs, Outs and AI item use", "## 7. Configuration and seeds",
    ];

    private static readonly RoleBand[] BandOrder = [RoleBand.Defender, RoleBand.Striker, RoleBand.Healer, RoleBand.Control];

    /// <summary>The report for <paramref name="battles"/>, played with <paramref name="config"/>.</summary>
    public static string Markdown(IReadOnlyList<SimBattle> battles, SimConfig config)
    {
        var md = new StringBuilder();
        var winCells = WinCells(battles);
        var bandRows = BandRows(battles);
        var abilities = AbilityRows(battles);
        var rare = abilities.Where(a => a.Flagged).ToArray();

        Line(md, "# Tactics balance report");
        Line(md);
        Line(md, "Generated by `Tactics.Sim` (spec §5.6): both sides AI-controlled, every battle deterministic from its seed.");
        Line(md);

        // 1. Summary
        Line(md, Headings[0]);
        Line(md);
        var won = battles.Count(b => b.Outcome == BattleOutcome.Won);
        var capped = battles.Count(b => b.Capped);
        Line(md, $"- **Battles:** {battles.Count} ({Count(battles.Select(b => b.Encounter))} encounter(s), levels {Join(config.Levels)}, "
                 + $"{Count(battles.Select(b => Party(b.Classes)))} parties, {config.Seeds} seed(s) each).");
        Line(md, $"- **Won:** {won} ({Pct(won, battles.Count)}). Lost: {battles.Count(b => b.Outcome == BattleOutcome.Lost)}, "
                 + $"of which {capped} stopped at the round cap of {config.RoundCap}. Fled: {battles.Count(b => b.Outcome == BattleOutcome.Fled)}.");
        if (battles.Count > 0)
        {
            var inTarget = battles.Count(b => b.Rounds >= TargetRounds.Min && b.Rounds <= TargetRounds.Max);
            Line(md, $"- **Rounds:** mean {Num(battles.Average(b => b.Rounds))}, median {Num(Median(battles.Select(b => (double)b.Rounds)))}; "
                     + $"{Pct(inTarget, battles.Count)} of battles within the {TargetRounds.Min}–{TargetRounds.Max} round target.");
        }
        Line(md, "- **Flags:**");
        Line(md, $"  - win rate outside {Pct(LowWinRate)}–{Pct(HighWinRate)}: {winCells.Count(c => c.Flag.Length > 0)} of {winCells.Length} encounter/level cells;");
        Line(md, $"  - mean battle length outside {TargetRounds.Min}–{TargetRounds.Max} rounds: {winCells.Count(c => c.RoundsFlag.Length > 0)} cells;");
        Line(md, $"  - role-band values more than ±{Pct(BandTolerance)} from the band mean: {bandRows.Count(r => r.Flagged)} of {bandRows.Length};");
        Line(md, $"  - abilities used in < {Pct(RareUse)} of legal turns: {rare.Length};");
        Line(md, $"  - battles stopped at the round cap: {capped}.");
        Line(md);

        // 2. Win rate
        Line(md, Headings[1]);
        Line(md);
        Line(md, $"Flags: **LOW** below {Pct(LowWinRate)}, **HIGH** above {Pct(HighWinRate)} (difficulty {config.Difficulty}). "
                 + "Encounters don't declare an intended level yet, so every level is judged.");
        Line(md);
        Line(md, "| Encounter | Level | Battles | Won | Win rate | Flag |");
        Line(md, "|---|---:|---:|---:|---:|---|");
        foreach (var c in winCells)
            Line(md, $"| {c.Encounter} | {c.Level} | {c.Battles.Length} | {c.Won} | {Pct(c.Won, c.Battles.Length)} | {c.Flag} |");
        Line(md);
        Line(md, "By party size:");
        Line(md);
        Line(md, "| Encounter | Level | Size | Battles | Win rate |");
        Line(md, "|---|---:|---:|---:|---:|");
        foreach (var g in battles.GroupBy(b => (b.Encounter, b.Level, b.Classes.Length))
                     .OrderBy(g => g.Key.Encounter, StringComparer.Ordinal).ThenBy(g => g.Key.Level).ThenBy(g => g.Key.Length))
            Line(md, $"| {g.Key.Encounter} | {g.Key.Level} | {g.Key.Length} | {g.Count()} | {Pct(g.Count(b => b.Outcome == BattleOutcome.Won), g.Count())} |");
        Line(md);

        // 3. Rounds
        Line(md, Headings[2]);
        Line(md);
        Line(md, $"Target: {TargetRounds.Min}–{TargetRounds.Max} rounds. Flags: **SHORT** / **LONG** when the mean is outside it, "
                 + $"**CAPPED** when any battle hit the round cap ({config.RoundCap}, counted as lost).");
        Line(md);
        Line(md, "| Encounter | Level | Mean | Median | Min | Max | In target | Capped | Flag |");
        Line(md, "|---|---:|---:|---:|---:|---:|---:|---:|---|");
        foreach (var c in winCells)
        {
            var r = c.Battles.Select(b => (double)b.Rounds).ToArray();
            var inTarget = c.Battles.Count(b => b.Rounds >= TargetRounds.Min && b.Rounds <= TargetRounds.Max);
            Line(md, $"| {c.Encounter} | {c.Level} | {Num(r.Average())} | {Num(Median(r))} | {r.Min()} | {r.Max()} | "
                     + $"{Pct(inTarget, r.Length)} | {c.Battles.Count(b => b.Capped)} | {c.RoundsFlag} |");
        }
        Line(md);

        // 4. Role bands
        Line(md, Headings[3]);
        Line(md);
        Line(md, "Each class's band measure at each level (the mean over the battles it fought, per member), against the mean of "
                 + $"its band's classes at that level; **FLAG** beyond ±{Pct(BandTolerance)}. Measures: Defender, damage mitigated per "
                 + "round (taken, plus misses against it × the mean hostile hit); Striker, damage per round; Healer, healing and "
                 + "revives per round; Control, enemy turns denied per battle. A band with one class present sits on its own mean.");
        Line(md);
        Line(md, "| Level | Band | Measure | Class | Value | Band mean | Deviation | Flag |");
        Line(md, "|---:|---|---|---|---:|---:|---:|---|");
        foreach (var r in bandRows)
            Line(md, $"| {r.Level} | {r.Band} | {MeasureName(r.Band)} | {r.Class} | {Num(r.Value)} | {Num(r.Mean)} | "
                     + $"{(r.Mean == 0 ? "–" : Signed(r.Value / r.Mean - 1))} | {(r.Flagged ? "**FLAG**" : "")} |");
        var absent = BandOrder.SelectMany(SimRunner.ClassesIn).Where(c => !battles.Any(b => b.PerClass.ContainsKey(c))).ToArray();
        if (absent.Length > 0)
        {
            Line(md);
            Line(md, $"Not in this sweep (no such class in the pack, or in no sampled party): {string.Join(", ", absent)}.");
        }
        Line(md);
        Line(md, "Every measure, by class and level:");
        Line(md);
        Line(md, "| Class | Band | Level | Battles | Damage / round | Healing / round | Mitigated / round | Turns denied |");
        Line(md, "|---|---|---:|---:|---:|---:|---:|---:|");
        foreach (var g in battles.SelectMany(b => b.PerClass.Select(p => (b.Level, Class: p.Key, Stats: p.Value)))
                     .GroupBy(x => (x.Class, x.Level))
                     .OrderBy(g => g.Key.Class, StringComparer.Ordinal).ThenBy(g => g.Key.Level))
            Line(md, $"| {g.Key.Class} | {SimRunner.BandOf(g.Key.Class)} | {g.Key.Level} | {g.Count()} | {Num(g.Average(x => x.Stats.DamagePerRound))} | "
                     + $"{Num(g.Average(x => x.Stats.HealingPerRound))} | {Num(g.Average(x => x.Stats.MitigatedPerRound))} | "
                     + $"{Num(g.Average(x => x.Stats.TurnsDenied))} |");
        Line(md);

        // 5. Abilities
        Line(md, Headings[4]);
        Line(md);
        Line(md, $"Abilities party members used in fewer than {Pct(RareUse)} of their turns where the ability was legal, over every "
                 + "battle (the built-in `common.*` actions are listed below but not flagged). Legal is judged at the start of each "
                 + "turn: an ability `Battle.Check` accepts on some unit or nearby tile, or refuses only for range or line of sight "
                 + "within the unit's Move plus the ability's range; reactions aren't counted.");
        Line(md);
        if (rare.Length == 0)
            Line(md, "None flagged.");
        else
        {
            Line(md, "| Ability | Used turns | Legal turns | Use rate |");
            Line(md, "|---|---:|---:|---:|");
            foreach (var a in rare)
                Line(md, $"| {a.Id} | {a.Used} | {a.Legal} | {Pct(a.Used, a.Legal)} |");
        }
        Line(md);
        Line(md, "Every ability party members could use:");
        Line(md);
        Line(md, "| Ability | Used turns | Legal turns | Use rate | Flag |");
        Line(md, "|---|---:|---:|---:|---|");
        foreach (var a in abilities)
            Line(md, $"| {a.Id} | {a.Used} | {a.Legal} | {Pct(a.Used, a.Legal)} | {(a.Flagged ? "**RARE**" : "")} |");
        Line(md);

        // 6. Downs, Outs, items
        Line(md, Headings[5]);
        Line(md);
        Line(md, "Party members Downed (each time) and Out, per battle; items the AI used (party members play with items off, so "
                 + "only enemies could use any).");
        Line(md);
        Line(md, "| Encounter | Level | Battles | Downs / battle | Outs / battle | Battles with an Out | AI item uses |");
        Line(md, "|---|---:|---:|---:|---:|---:|---:|");
        foreach (var c in winCells)
            Line(md, $"| {c.Encounter} | {c.Level} | {c.Battles.Length} | {Num(c.Battles.Average(b => b.Downs))} | "
                     + $"{Num(c.Battles.Average(b => b.Outs))} | {c.Battles.Count(b => b.Outs > 0)} | {c.Battles.Sum(b => b.AiItemUses)} |");
        Line(md);

        // 7. Configuration
        Line(md, Headings[6]);
        Line(md);
        Line(md, "```");
        Line(md, "dotnet run -c Release --project games/Tactics/Tactics.Sim -- \\");
        Line(md, $"  --encounters {string.Join(",", config.Encounters)} --levels {string.Join(",", config.Levels)} "
                 + $"--sizes {string.Join(",", config.PartySizes)} --parties {config.PartiesPerSize} \\");
        Line(md, $"  --seeds {config.Seeds} --difficulty {config.Difficulty} --round-cap {config.RoundCap}");
        Line(md, "```");
        Line(md);
        Line(md, $"- **Encounters:** {string.Join(", ", config.Encounters)}.");
        Line(md, $"- **Levels:** {Join(config.Levels)}. **Party sizes:** {Join(config.PartySizes)} ({config.PartiesPerSize} sampled parties per size).");
        Line(md, $"- **Seeds:** {(config.Seeds == 1 ? "1" : $"1–{config.Seeds}")} for every encounter, level and party (the battle's `Battle.Start` seed).");
        Line(md, $"- **Difficulty:** {config.Difficulty}. **Round cap:** {config.RoundCap} (a battle still going after it counts as lost).");
        Line(md, $"- **Parties:** human characters from `SheetBuilder.DefaultCharacter` (no subclass, default picks), playing the "
                 + "profile their class's `aiTags` name (healer → `healer`, caster or control → `caster`, ranged → `archer`, striker "
                 + "→ `skirmisher`, otherwise `brute`) with items off; enemies play their monster's profile. Party compositions "
                 + $"are drawn from every combination with at least one healer or defender and at most {SimRunner.MaxCopies} of a class, "
                 + $"by a generator seeded {SimRunner.PartySeed}:");
        foreach (var party in battles.Select(b => b.Classes).DistinctBy(Party).OrderBy(p => p.Length).ThenBy(Party, StringComparer.Ordinal))
            Line(md, $"  - {party.Length}: {string.Join(", ", party)}");
        return md.ToString();
    }

    // ---- Tables -------------------------------------------------------------------------------------------------------

    private sealed record WinCell(string Encounter, int Level, SimBattle[] Battles, int Won, string Flag, string RoundsFlag);

    private static WinCell[] WinCells(IReadOnlyList<SimBattle> battles)
        => [.. battles.GroupBy(b => (b.Encounter, b.Level))
            .OrderBy(g => g.Key.Encounter, StringComparer.Ordinal).ThenBy(g => g.Key.Level)
            .Select(g =>
            {
                var all = g.ToArray();
                var won = all.Count(b => b.Outcome == BattleOutcome.Won);
                var rate = (double)won / all.Length;
                var flag = rate < LowWinRate ? "**LOW**" : rate > HighWinRate ? "**HIGH**" : "";
                var mean = all.Average(b => b.Rounds);
                var rounds = string.Join(" ", new[]
                {
                    mean < TargetRounds.Min ? "**SHORT**" : mean > TargetRounds.Max ? "**LONG**" : "",
                    all.Any(b => b.Capped) ? "**CAPPED**" : "",
                }.Where(s => s.Length > 0));
                return new WinCell(g.Key.Encounter, g.Key.Level, all, won, flag, rounds);
            })];

    private sealed record BandRow(int Level, RoleBand Band, string Class, double Value, double Mean, bool Flagged);

    private static BandRow[] BandRows(IReadOnlyList<SimBattle> battles)
    {
        var rows = new List<BandRow>();
        foreach (var level in battles.Select(b => b.Level).Distinct().Order())
            foreach (var band in BandOrder)
            {
                var values = battles.Where(b => b.Level == level)
                    .SelectMany(b => b.PerClass.Where(p => SimRunner.BandOf(p.Key) == band))
                    .GroupBy(p => p.Key, StringComparer.Ordinal)
                    .OrderBy(g => g.Key, StringComparer.Ordinal)
                    .Select(g => (Class: g.Key, Value: g.Average(p => Measure(band, p.Value))))
                    .ToArray();
                if (values.Length == 0)
                    continue;
                var mean = values.Average(v => v.Value);
                rows.AddRange(values.Select(v => new BandRow(level, band, v.Class, v.Value, mean,
                    mean > 0 ? Math.Abs(v.Value / mean - 1) > BandTolerance : v.Value != 0)));
            }
        return [.. rows];
    }

    private static double Measure(RoleBand band, ClassStats s) => band switch
    {
        RoleBand.Defender => s.MitigatedPerRound,
        RoleBand.Striker => s.DamagePerRound,
        RoleBand.Healer => s.HealingPerRound,
        RoleBand.Control => s.TurnsDenied,
        _ => 0,
    };

    private static string MeasureName(RoleBand band) => band switch
    {
        RoleBand.Defender => "mitigated / round",
        RoleBand.Striker => "damage / round",
        RoleBand.Healer => "healing / round",
        RoleBand.Control => "turns denied / battle",
        _ => "",
    };

    private sealed record AbilityRow(AbilityId Id, int Used, int Legal, bool Flagged);

    private static AbilityRow[] AbilityRows(IReadOnlyList<SimBattle> battles)
        => [.. battles.SelectMany(b => b.Abilities)
            .GroupBy(a => a.Key)
            .OrderBy(g => g.Key)
            .Select(g =>
            {
                var used = g.Sum(a => a.Value.Used);
                var legal = g.Sum(a => a.Value.Legal);
                var common = g.Key.Value.StartsWith("common.", StringComparison.Ordinal);
                return new AbilityRow(g.Key, used, legal, !common && legal > 0 && (double)used / legal < RareUse);
            })];

    // ---- Formatting ---------------------------------------------------------------------------------------------------

    private static void Line(StringBuilder md, string text = "") => md.Append(text).Append('\n');

    private static string Party(ImmutableArray<string> classes) => string.Join(",", classes);

    private static int Count(IEnumerable<string> items) => items.Distinct(StringComparer.Ordinal).Count();

    private static string Join(ImmutableArray<int> values) => string.Join(", ", values);

    private static string Num(double value) => value.ToString("0.0", CultureInfo.InvariantCulture);

    private static string Pct(double share) => (100 * share).ToString("0", CultureInfo.InvariantCulture) + "%";

    private static string Pct(int part, int whole) => whole == 0 ? "–" : (100.0 * part / whole).ToString("0.0", CultureInfo.InvariantCulture) + "%";

    private static string Signed(double share) => (share >= 0 ? "+" : "") + (100 * share).ToString("0.0", CultureInfo.InvariantCulture) + "%";

    private static double Median(IEnumerable<double> values)
    {
        var sorted = values.Order().ToArray();
        if (sorted.Length == 0)
            return 0;
        var mid = sorted.Length / 2;
        return sorted.Length % 2 == 1 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
    }
}
