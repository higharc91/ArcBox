import { afterEach, expect, it, vi } from "vitest";
import { act, cleanup, fireEvent, render, screen } from "@testing-library/preact";
import { App } from "../src/App";
import { Session } from "../src/session/session";
import { FakeTransport } from "./fakeTransport";
import lobby from "./fixtures/lobby.json";
import choice from "./fixtures/choice.json";
afterEach(() => { cleanup(); vi.useRealTimers(); });
it("pauses the last game through reconnect and close, offers help after 15s, then resumes a fresh snapshot", async () => {
  vi.useFakeTimers();
  const t = new FakeTransport();
  const entries = new Map<string, string>();
  const s = new Session(t, { getItem: k => entries.get(k) ?? null, setItem: (k,v) => { entries.set(k,v); }, removeItem: k => { entries.delete(k); } });
  t.responders.TakeSeat = () => {
    t.fire("LobbyChanged", { ...lobby, inGame: true });
    t.fire("ControllerView", choice);
    return { code: "BCDF", playerId: "p1", secret: "secret" };
  };
  await s.joinNew("Alex", "BCDF");
  render(<App session={s} />);
  act(() => t.fireReconnecting());
  expect(screen.getByText(/Reconnecting…/)).toBeTruthy();
  expect(screen.getByText("Pick your driver")).toBeTruthy();
  const control = screen.getByRole("button", { name: /Piastri/ });
  expect(control.closest("fieldset")?.disabled).toBe(true);
  fireEvent.click(control);
  await s.send("v1", { choice: "PIA" });
  expect(t.methods()).not.toContain("SendInput");
  act(() => { vi.advanceTimersByTime(15000); });
  expect(screen.getByText(/Wi-Fi/)).toBeTruthy();
  t.failStart = new Error("offline");
  act(() => t.fireClose());
  expect(screen.getByText("Pick your driver")).toBeTruthy();
  await act(async () => { fireEvent.click(screen.getByRole("button", { name: "Try again" })); });
  expect(t.starts).toBe(2);
  t.failStart = null;
  let complete!: () => void;
  t.responders.Rejoin = () => new Promise<void>(resolve => { complete = resolve; });
  await act(async () => { t.fireReconnected(); await Promise.resolve(); });
  expect(control.closest("fieldset")?.disabled).toBe(true);
  await act(async () => {
    t.fire("ControllerView", { ...choice, viewId: "v2" });
    complete(); await Promise.resolve(); await Promise.resolve();
  });
  expect(screen.getByText("Back in the game")).toBeTruthy();
  expect(control.closest("fieldset")?.disabled).toBe(false);
  await s.send("v2", { choice: "PIA" });
  expect(t.invokes.at(-1)?.args[0]).toBe("v2");
  act(() => { vi.advanceTimersByTime(3000); });
  expect(screen.queryByText("Back in the game")).toBeNull();
  s.dispose();
});
