const fs = require('node:fs');
const path = require('node:path');
const read = name => JSON.parse(fs.readFileSync(path.join(__dirname,name),'utf8'));
const batch = read('batch-requests.json');
const approvals = read('approvals.json');
const prior = read('batch-progress.json');
const completed = [], pending = [];
let spent = 0;
for (const req of batch.requests) {
  const filename = `generated/${req.id}-result.json`;
  if (!fs.existsSync(path.join(__dirname,filename))) { pending.push(req.id); continue; }
  const r = read(filename);
  if (r.status !== 'success' || !fs.existsSync(path.join(__dirname,`generated/${req.id}.png`))) { pending.push(req.id); continue; }
  spent += r.cuCost;
  completed.push({id:req.id,job_id:r.jobId,asset_id:r.assetIds[0],cuCost:r.cuCost,reused:r.reused??false,output:`generated/${req.id}.png`});
}
const limit = approvals.concept_batch_2026_11_03.maximumCU;
const supplements = [];
if (fs.existsSync(path.join(__dirname,'supplements/child-b-result.json'))) {
  const r = read('supplements/child-b-result.json');
  if (r.status==='success' && fs.existsSync(path.join(__dirname,'supplements/child-b.png'))) {
    spent += r.cuCost;
    supplements.push({id:'townsfolk_child_b_body',asset_id:r.assetIds[0],job_id:r.jobId,cuCost:r.cuCost,output:'supplements/child-b.png'});
  }
}
if (spent>limit) throw Error('Budget exceeded');
const progress = { ...prior, status:pending.length?'partially_complete':'concept_outputs_ready_for_review',
  batch_spentCU:spent,remaining_authorizedCU:limit-spent,total_with_breeCU:spent+read('bree-result.json').actualCU,
  completed,pending,supplemental_views:supplements,inflight_job_ids:[],
  provider_refusal_history:prior.provider_refusal_history??(prior.provider_refusal?[prior.provider_refusal]:[]),
  resume:'Run resume-batch.cjs before any new generation. Reconcile existing jobs and recover remote concepts first. Completed images must never be regenerated by a resume.',
  design_approvals_pending:completed.filter(r=>approvals[r.id]?.status!=='approved').map(r=>r.id) };
delete progress.provider_refusal;
fs.writeFileSync(path.join(__dirname,'batch-progress.json'),JSON.stringify(progress,null,2)+'\n');
console.log(`${completed.length} batch outputs saved (${completed.filter(x=>x.reused).length} recovered); ${pending.length} missing; ${spent} CU batch spend.`);
