"""Colour ramps for ArcBox Tactics pixel art.

Every part is drawn with (slot, shade) pairs instead of fixed colours. A *ramp* is the list of colours one slot
takes, from darkest (shade 0) to lightest (shade RAMP_LEN - 1). A *palette* maps slot names to ramps, so the same
drawing becomes any team, class or skin by swapping the palette.

Ramps are generated by hue shifting: shadows drift towards blue/violet and gain saturation, highlights drift towards
yellow and lose a little saturation. That is what makes pixel art read as lit rather than merely darkened.
"""
from __future__ import annotations

import colorsys

RAMP_LEN = 6
"""Shades per ramp: 0 deep shadow, 1 shadow, 2 base-dark, 3 base, 4 light, 5 highlight."""

BASE = 3
"""The shade a part's flat colour uses; outlines and shadows count down from here, highlights up."""


def _hex(rgb: tuple[float, float, float]) -> str:
    r, g, b = (max(0, min(255, round(c * 255))) for c in rgb)
    return f"#{r:02x}{g:02x}{b:02x}"


def _rgb(hex_colour: str) -> tuple[float, float, float]:
    h = hex_colour.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))  # type: ignore[return-value]


def _shift_hue(h: float, towards: float, amount: float) -> float:
    """Moves hue h (0..1) towards `towards` by at most `amount` turns, the short way round."""
    d = ((towards - h + 0.5) % 1.0) - 0.5
    step = max(-amount, min(amount, d))
    return (h + step) % 1.0


def ramp(base: str, *, shift: float = 0.06, spread: float = 1.0, sat_boost: float = 0.12) -> list[str]:
    """A RAMP_LEN ramp around `base` (used as shade BASE), hue-shifted.

    shift      how far (in hue turns) the darkest shade moves towards violet and the lightest towards yellow.
    spread     scales the value steps; <1 for low-contrast materials (cloth), >1 for shiny ones (metal).
    sat_boost  extra saturation in the shadows.
    """
    r, g, b = _rgb(base)
    h, s, v = colorsys.rgb_to_hsv(r, g, b)
    out: list[str] = []
    for i in range(RAMP_LEN):
        k = i - BASE  # -3..+2
        if k < 0:
            t = -k / BASE
            hh = _shift_hue(h, 0.70, shift * t)  # towards blue-violet
            ss = min(1.0, s + sat_boost * t)
            # Geometric darkening keeps the deepest shade readable (never collapses to black).
            vv = max(0.07, v * (1 - 0.17 * spread) ** (-k))
        elif k > 0:
            t = k / (RAMP_LEN - 1 - BASE)
            hh = _shift_hue(h, 0.13, shift * 0.6 * t)  # towards warm yellow, gentler than the shadow shift
            ss = max(0.0, s * (1 - 0.30 * t))
            vv = min(1.0, v + (1 - v) * 0.42 * spread * t + 0.035 * k)
        else:
            hh, ss, vv = h, s, v
        out.append(_hex(colorsys.hsv_to_rgb(hh, ss, vv)))
    return out


